def render_markdown(
    conversation: ExampleConversation, turns: Sequence[TurnRecord], metadata: Metadata
) -> str:
    header = [
        f"# {conversation.title}",
        "",
        conversation.scenario,
        "",
        f"- **Model:** `{metadata.model}`",
        f"- **AGENT_NOW:** `{metadata.agent_now}`",
        f"- **Git commit:** `{metadata.git_hash}`",
        f"- **Generated at:** `{metadata.generated_at}`",
        f"- {GENERATION_NOTE}",
        "",
    ]
    sections = [render_turn(index, turn) for index, turn in enumerate(turns, start=1)]
    return "\n".join(header + sections)


def render_turn(index: int, turn: TurnRecord) -> str:
    tools = ", ".join(turn.reply.tools_called) or NO_TOOLS_LABEL
    blocked = "sim" if turn.reply.blocked else "não"
    return "\n".join(
        [
            f"## Turno {index}",
            "",
            f"**Cliente:** {turn.message}",
            "",
            "**Lia:**",
            "",
            turn.reply.text,
            "",
            f"_Ferramentas chamadas: {tools} · Bloqueado pelo plugin de segurança: {blocked}_",
            "",
        ]
    )


def is_retryable(error: APIError) -> bool:
    return error.code in RETRYABLE_STATUS_CODES


async def respond_with_retry(
    responder: Responder, session_id: str, message: str, sleep: Sleep, label: str
) -> AgentReply:
    for delay_s in (*RETRY_DELAYS_S, None):
        try:
            return await responder(session_id, message)
        except APIError as error:
            if not is_retryable(error):
                raise
            if delay_s is None:
                raise GenerationError(
                    f"{label}: model still returned {error.code} after "
                    f"{len(RETRY_DELAYS_S)} retries for turn {message!r}; try again later."
                ) from error
            print(f"  model returned {error.code}; retrying in {delay_s:.0f}s", file=sys.stderr)
            await sleep(delay_s)
    raise AssertionError("unreachable")  # pragma: no cover


def new_session_id(conversation: ExampleConversation) -> str:
    stem = Path(conversation.file_name).stem
    return f"examples-{stem}-{uuid.uuid4().hex[:SESSION_SUFFIX_LENGTH]}"


async def run_conversation(
    conversation: ExampleConversation, responder: Responder, sleep: Sleep, turn_delay_s: float
) -> list[TurnRecord]:
    session_id = new_session_id(conversation)
    records: list[TurnRecord] = []
    for index, message in enumerate(conversation.turns):
        if index > 0:
            await sleep(turn_delay_s)
        reply = await respond_with_retry(
            responder, session_id, message, sleep, conversation.file_name
        )
        records.append(TurnRecord(message=message, reply=reply))
    return records


async def generate(
    conversations: Sequence[ExampleConversation],
    responder: Responder,
    output_dir: Path,
    metadata: Metadata,
    sleep: Sleep = asyncio.sleep,
    turn_delay_s: float = DEFAULT_TURN_DELAY_S,
) -> list[Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for index, conversation in enumerate(conversations):
        if index > 0:
            await sleep(turn_delay_s)
        print(f"Generating {conversation.file_name}...")
        turns = await run_conversation(conversation, responder, sleep, turn_delay_s)
        path = output_dir / conversation.file_name
        path.write_text(render_markdown(conversation, turns, metadata), encoding="utf-8")
        written.append(path)
    return written


def select_conversations(
    conversations: Sequence[ExampleConversation], only: str | None
) -> tuple[ExampleConversation, ...]:
    if only is None:
        return tuple(conversations)
    selected = tuple(c for c in conversations if c.file_name.startswith(only))
    if not selected:
        raise GenerationError(f"No example conversation matches --only {only!r}.")
    return selected


def git_short_hash() -> str:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return UNKNOWN_GIT_HASH
    return result.stdout.strip() or UNKNOWN_GIT_HASH


def pin_agent_clock() -> None:
    os.environ["AGENT_NOW"] = AGENT_NOW
    get_settings.cache_clear()


def build_metadata() -> Metadata:
    return Metadata(
        model=get_settings().model,
        agent_now=AGENT_NOW,
        git_hash=git_short_hash(),
        generated_at=datetime.now(UTC).isoformat(timespec="seconds"),
    )


async def agent_responder(session_id: str, message: str) -> AgentReply:
    from musical_agent.agent.agent import respond

    return await respond(session_id, message)


def parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate example transcripts.")
    parser.add_argument("--only", help="file name prefix of a single conversation, e.g. 04")
    parser.add_argument("--turn-delay", type=float, default=DEFAULT_TURN_DELAY_S)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    return parser.parse_args(argv)


def main(
    argv: Sequence[str] | None = None,
    responder: Responder | None = None,
    sleep: Sleep | None = None,
) -> int:
    args = parse_args(argv)
    pin_agent_clock()
    try:
        conversations = select_conversations(CONVERSATIONS, args.only)
        written = asyncio.run(
            generate(
                conversations,
                responder or agent_responder,
                args.output_dir,
                build_metadata(),
                sleep or asyncio.sleep,
                args.turn_delay,
            )
        )
    except GenerationError as error:
        print(f"error: {error}", file=sys.stderr)
        return EXIT_FAILURE
    for path in written:
        print(f"Wrote {path}")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
