"""Generate the example transcripts in `examples/` from real conversations with the agent.

Each scripted conversation runs in a fresh session against the real model with the clock
pinned to `AGENT_NOW`, and the transcript is written verbatim (responses are never edited
by hand). Turns are paced to respect the free-tier rate limit, and 429/503 errors are
retried with increasing delays.

Usage (from the repo root):
    uv run python scripts/generate_examples.py [--only 04] [--turn-delay 36] [--output-dir examples]
"""

from __future__ import annotations

import argparse
import asyncio
import os
import subprocess
import sys
import uuid
from collections.abc import Awaitable, Callable, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from google.genai.errors import APIError

from musical_agent.config import PROJECT_ROOT, get_settings
from musical_agent.types import AgentReply

AGENT_NOW = "2026-03-25T10:00:00-04:00"
DEFAULT_TURN_DELAY_S = 15.0
DEFAULT_OUTPUT_DIR = PROJECT_ROOT / "examples"
RETRYABLE_STATUS_CODES = frozenset({429, 503})
RETRY_DELAYS_S = (40.0, 60.0, 90.0)
SESSION_SUFFIX_LENGTH = 8
UNKNOWN_GIT_HASH = "unknown"
NO_TOOLS_LABEL = "nenhuma"
GENERATION_NOTE = "Generated by scripts/generate_examples.py; responses are not edited by hand."
EXIT_OK = 0
EXIT_FAILURE = 1

Responder = Callable[[str, str], Awaitable[AgentReply]]
Sleep = Callable[[float], Awaitable[None]]


class GenerationError(RuntimeError):
    pass


@dataclass(frozen=True)
class ExampleConversation:
    file_name: str
    title: str
    scenario: str
    turns: tuple[str, ...]


@dataclass(frozen=True)
class TurnRecord:
    message: str
    reply: AgentReply


@dataclass(frozen=True)
class Metadata:
    model: str
    agent_now: str
    git_hash: str
    generated_at: str


